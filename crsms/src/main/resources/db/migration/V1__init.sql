CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dtype VARCHAR(31) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    department VARCHAR(120),
    role VARCHAR(20) NOT NULL,
    account_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role CHECK (role IN ('STUDENT', 'FACULTY', 'STAFF', 'ADMIN')),
    CONSTRAINT chk_users_status CHECK (account_status IN ('ACTIVE', 'DEACTIVATED'))
);

CREATE TABLE students (
    id BIGINT PRIMARY KEY,
    student_number VARCHAR(40) NOT NULL,
    CONSTRAINT fk_students_user FOREIGN KEY (id) REFERENCES users (id),
    CONSTRAINT uq_students_number UNIQUE (student_number)
);

CREATE TABLE faculty (
    id BIGINT PRIMARY KEY,
    employee_number VARCHAR(40) NOT NULL,
    designation VARCHAR(80),
    CONSTRAINT fk_faculty_user FOREIGN KEY (id) REFERENCES users (id),
    CONSTRAINT uq_faculty_number UNIQUE (employee_number)
);

CREATE TABLE staff (
    id BIGINT PRIMARY KEY,
    employee_number VARCHAR(40) NOT NULL,
    office VARCHAR(80),
    CONSTRAINT fk_staff_user FOREIGN KEY (id) REFERENCES users (id),
    CONSTRAINT uq_staff_number UNIQUE (employee_number)
);

CREATE TABLE resource_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT uq_category_name UNIQUE (name)
);

CREATE TABLE resource_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    title VARCHAR(140) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    pricing_type VARCHAR(20) NOT NULL,
    rate NUMERIC(12, 2) NOT NULL,
    listing_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_listing_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_listing_category FOREIGN KEY (category_id) REFERENCES resource_categories (id),
    CONSTRAINT chk_listing_rate CHECK (rate >= 0),
    CONSTRAINT chk_listing_pricing CHECK (pricing_type IN ('FREE', 'HOURLY', 'DAILY')),
    CONSTRAINT chk_listing_status CHECK (listing_status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_listings_owner ON resource_listings (owner_id);
CREATE INDEX idx_listings_category ON resource_listings (category_id);
CREATE INDEX idx_listings_status ON resource_listings (listing_status);

CREATE TABLE resource_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    asset_code VARCHAR(40) NOT NULL,
    condition VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    location_note VARCHAR(200),
    CONSTRAINT fk_unit_listing FOREIGN KEY (listing_id) REFERENCES resource_listings (id),
    CONSTRAINT uq_unit_asset UNIQUE (asset_code),
    CONSTRAINT chk_unit_condition CHECK (condition IN ('NEW', 'GOOD', 'FAIR', 'DAMAGED')),
    CONSTRAINT chk_unit_status CHECK (status IN (
        'AVAILABLE', 'RESERVED', 'BORROWED', 'MAINTENANCE_REQUIRED',
        'UNDER_REPAIR', 'INACTIVE', 'LOST'))
);

CREATE INDEX idx_units_listing ON resource_units (listing_id);
CREATE INDEX idx_units_status ON resource_units (status);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_res_borrower FOREIGN KEY (borrower_id) REFERENCES users (id),
    CONSTRAINT fk_res_unit FOREIGN KEY (unit_id) REFERENCES resource_units (id),
    CONSTRAINT chk_res_time CHECK (end_at > start_at),
    CONSTRAINT chk_res_status CHECK (status IN (
        'REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED', 'EXPIRED', 'ACTIVE', 'RETURNED'))
);

CREATE INDEX idx_res_unit_status ON reservations (unit_id, status);
CREATE INDEX idx_res_borrower ON reservations (borrower_id);
CREATE INDEX idx_res_window ON reservations (unit_id, start_at, end_at);

CREATE TABLE borrowing_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    picked_up_at TIMESTAMP NOT NULL,
    due_at TIMESTAMP NOT NULL,
    returned_at TIMESTAMP,
    charge_amount NUMERIC(12, 2) NOT NULL,
    late BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_borrow_res FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    CONSTRAINT fk_borrow_user FOREIGN KEY (borrower_id) REFERENCES users (id),
    CONSTRAINT fk_borrow_unit FOREIGN KEY (unit_id) REFERENCES resource_units (id),
    CONSTRAINT uq_borrow_reservation UNIQUE (reservation_id),
    CONSTRAINT chk_charge_nonneg CHECK (charge_amount >= 0),
    CONSTRAINT chk_borrow_status CHECK (status IN ('ACTIVE', 'RETURNED', 'OVERDUE'))
);

CREATE INDEX idx_borrow_status ON borrowing_records (status);
CREATE INDEX idx_borrow_borrower ON borrowing_records (borrower_id);

CREATE TABLE maintenance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    reporter_id BIGINT NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    admin_note VARCHAR(2000),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_maint_unit FOREIGN KEY (unit_id) REFERENCES resource_units (id),
    CONSTRAINT fk_maint_reporter FOREIGN KEY (reporter_id) REFERENCES users (id),
    CONSTRAINT chk_maint_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'REJECTED'))
);

CREATE INDEX idx_maint_status ON maintenance_requests (status);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrowing_id BIGINT NOT NULL,
    reviewer_id BIGINT NOT NULL,
    rating INT NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_review_borrow FOREIGN KEY (borrowing_id) REFERENCES borrowing_records (id),
    CONSTRAINT fk_review_user FOREIGN KEY (reviewer_id) REFERENCES users (id),
    CONSTRAINT uq_review_borrowing UNIQUE (borrowing_id),
    CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrowing_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_borrow FOREIGN KEY (borrowing_id) REFERENCES borrowing_records (id),
    CONSTRAINT uq_payment_borrowing UNIQUE (borrowing_id),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0),
    CONSTRAINT chk_payment_status CHECK (status IN ('SIMULATED', 'WAIVED'))
);

