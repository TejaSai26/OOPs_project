-- Extends the relational schema. PostgreSQL remains a relational store mapped by JPA;
-- this script is not an object-database migration.

ALTER TABLE reservations DROP CONSTRAINT chk_res_status;
ALTER TABLE reservations ADD CONSTRAINT chk_res_status CHECK (status IN (
    'REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED', 'EXPIRED', 'ACTIVE', 'RETURNED', 'WAITLISTED'));
ALTER TABLE reservations ADD COLUMN decision_note VARCHAR(500);
ALTER TABLE reservations ADD COLUMN queue_position INT;

ALTER TABLE resource_units DROP CONSTRAINT chk_unit_condition;
ALTER TABLE resource_units ADD CONSTRAINT chk_unit_condition CHECK (condition IN (
    'NEW', 'GOOD', 'FAIR', 'DAMAGED', 'UNDER_MAINTENANCE'));

ALTER TABLE resource_listings ADD COLUMN borrow_count BIGINT DEFAULT 0 NOT NULL;

ALTER TABLE borrowing_records ADD COLUMN penalty_amount NUMERIC(12, 2) DEFAULT 0 NOT NULL;
ALTER TABLE borrowing_records ADD COLUMN condition_out VARCHAR(20);
ALTER TABLE borrowing_records ADD COLUMN condition_in VARCHAR(20);
ALTER TABLE borrowing_records ADD COLUMN reminder_sent BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE borrowing_records ADD COLUMN overdue_notified BOOLEAN DEFAULT FALSE NOT NULL;

ALTER TABLE maintenance_requests ADD COLUMN assignee_id BIGINT;
ALTER TABLE maintenance_requests ADD CONSTRAINT fk_maint_assignee FOREIGN KEY (assignee_id) REFERENCES users (id);
ALTER TABLE maintenance_requests ADD COLUMN repair_cost NUMERIC(12, 2);
ALTER TABLE maintenance_requests ADD COLUMN photo_ref VARCHAR(500);
ALTER TABLE maintenance_requests ADD CONSTRAINT chk_repair_cost CHECK (repair_cost IS NULL OR repair_cost >= 0);

CREATE TABLE penalties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrowing_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    payment_status VARCHAR(20) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    waived_reason VARCHAR(500),
    waived_by_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_pen_borrow FOREIGN KEY (borrowing_id) REFERENCES borrowing_records (id),
    CONSTRAINT fk_pen_user FOREIGN KEY (borrower_id) REFERENCES users (id),
    CONSTRAINT fk_pen_waiver FOREIGN KEY (waived_by_id) REFERENCES users (id),
    CONSTRAINT uq_penalty_borrowing UNIQUE (borrowing_id),
    CONSTRAINT chk_pen_amount CHECK (amount >= 0),
    CONSTRAINT chk_pen_status CHECK (payment_status IN ('UNPAID', 'PAID', 'WAIVED'))
);

CREATE INDEX idx_pen_borrower ON penalties (borrower_id, payment_status);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    read_flag BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    entity_type VARCHAR(40),
    entity_id BIGINT,
    CONSTRAINT fk_notif_user FOREIGN KEY (recipient_id) REFERENCES users (id)
);

CREATE INDEX idx_notif_user ON notifications (recipient_id, read_flag, created_at);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT,
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id VARCHAR(40),
    description VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES users (id)
);

CREATE INDEX idx_audit_created ON audit_logs (created_at);
CREATE INDEX idx_audit_action ON audit_logs (action);

CREATE TABLE resource_condition_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    condition VARCHAR(20) NOT NULL,
    phase VARCHAR(30) NOT NULL,
    note VARCHAR(1000),
    photo_ref VARCHAR(500),
    recorded_by_id BIGINT,
    recorded_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_cond_unit FOREIGN KEY (unit_id) REFERENCES resource_units (id),
    CONSTRAINT fk_cond_user FOREIGN KEY (recorded_by_id) REFERENCES users (id),
    CONSTRAINT chk_cond_hist CHECK (condition IN ('NEW', 'GOOD', 'FAIR', 'DAMAGED', 'UNDER_MAINTENANCE')),
    CONSTRAINT chk_cond_phase CHECK (phase IN ('INITIAL', 'BEFORE_BORROW', 'AFTER_RETURN', 'DAMAGE_REPORT', 'MAINTENANCE'))
);

CREATE INDEX idx_cond_unit ON resource_condition_history (unit_id, recorded_at);

CREATE TABLE system_settings (
    id BIGINT PRIMARY KEY,
    late_fee_multiplier NUMERIC(8, 2) NOT NULL,
    reminder_hours INT NOT NULL,
    CONSTRAINT chk_multiplier CHECK (late_fee_multiplier >= 0 AND late_fee_multiplier <= 10),
    CONSTRAINT chk_reminder CHECK (reminder_hours BETWEEN 1 AND 168)
);

